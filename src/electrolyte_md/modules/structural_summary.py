def make_combined_metric_plot(
    summary_table,
    metric,
    ylabel,
    filename,
):
    """Plot a block-averaged structural metric for all systems."""

    subset = summary_table[
        summary_table["metric"] == metric
    ].copy()

    if subset.empty:
        print(
            f"Skipping missing combined metric: {metric}"
        )
        return

    subset = sort_compositions(subset)

    fig, ax = plt.subplots(
        figsize=(7.2, 5.0)
    )

    for metal, metal_data in subset.groupby(
        "metal_species",
        observed=True,
    ):

        metal_data = metal_data.sort_values(
            "composition"
        )

        x = np.arange(
            len(metal_data)
        )

        ax.errorbar(
            x,
            metal_data["mean"],
            yerr=metal_data["block_std"],
            marker="o",
            capsize=4,
            label=metal,
        )

        ax.set_xticks(x)

        ax.set_xticklabels(
            metal_data["composition"].astype(str)
        )

    ax.set_xlabel(
        "IL:salt composition"
    )

    ax.set_ylabel(ylabel)

    ax.legend(
        frameon=False
    )

    ax.grid(
        axis="y",
        alpha=0.25,
    )

    fig.tight_layout()

    save_figure(
        fig,
        filename,
    )


def make_combined_state_plot(state_summary):
    """Plot P/PT/T/F state populations across systems."""

    data = sort_compositions(
        state_summary
    )

    systems = (
        data[
            [
                "metal_species",
                "composition",
            ]
        ]
        .drop_duplicates()
        .reset_index(drop=True)
    )

    labels = [
        f"{row.metal_species}\n{row.composition}"
        for row in systems.itertuples()
    ]

    x = np.arange(
        len(systems)
    )

    state_order = [
        "P",
        "PT",
        "T",
        "F",
    ]

    bottom = np.zeros(
        len(systems)
    )

    fig, ax = plt.subplots(
        figsize=(9.0, 5.3)
    )

    for state in state_order:

        heights = []

        for row in systems.itertuples():

            selection = data[
                (data["metal_species"]
                 == row.metal_species)
                &
                (data["composition"]
                 == row.composition)
                &
                (data["state"] == state)
            ]

            if selection.empty:
                heights.append(0.0)
            else:
                heights.append(
                    selection[
                        "mean_fraction"
                    ].iloc[0]
                )

        heights = np.asarray(
            heights
        )

        ax.bar(
            x,
            heights,
            bottom=bottom,
            label=state,
        )

        bottom += heights

    ax.set_xticks(x)
    ax.set_xticklabels(labels)

    ax.set_ylabel(
        "Coordination-state fraction"
    )

    ax.set_ylim(
        0,
        1,
    )

    ax.legend(
        frameon=False,
        ncol=4,
    )

    ax.grid(
        axis="y",
        alpha=0.25,
    )

    fig.tight_layout()

    save_figure(
        fig,
        "combined_coordination_state_fractions",
    )


