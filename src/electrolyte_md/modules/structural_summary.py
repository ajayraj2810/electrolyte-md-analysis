def analyze_system(system_name, config):
    """Analyze one master structural database."""

    print("\n" + "=" * 78)
    print(f"Analyzing structural database: {system_name}")
    print("=" * 78)

    master = read_master_database(
        config["master_file"]
    )

    frames = read_table(
        config["frame_file"]
    )

    tfsi_bridging = read_table(
        config["tfsi_bridging_file"]
    )

    peo_bridging = read_table(
        config["peo_bridging_file"]
    )

    clusters = read_table(
        config["cluster_file"]
    )

    master = discard_initial_frames(
        master,
        DISCARD_INITIAL_FRACTION,
    )

    frames = discard_initial_frames(
        frames,
        DISCARD_INITIAL_FRACTION,
    )

    tfsi_bridging = discard_initial_frames(
        tfsi_bridging,
        DISCARD_INITIAL_FRACTION,
    )

    peo_bridging = discard_initial_frames(
        peo_bridging,
        DISCARD_INITIAL_FRACTION,
    )

    clusters = discard_initial_frames(
        clusters,
        DISCARD_INITIAL_FRACTION,
    )

    master = assign_frame_blocks(
        master,
        N_BLOCKS,
    )

    frames = assign_frame_blocks(
        frames,
        N_BLOCKS,
    )

    tfsi_bridging = assign_frame_blocks(
        tfsi_bridging,
        N_BLOCKS,
    )

    peo_bridging = assign_frame_blocks(
        peo_bridging,
        N_BLOCKS,
    )

    clusters = assign_frame_blocks(
        clusters,
        N_BLOCKS,
    )

    metal = config["metal"]
    composition = config["composition"]

    system_output_dir = OUTPUT_DIR / system_name

    system_output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ========================================================
    # 1. FRAME-LEVEL BLOCK AVERAGES
    # ========================================================

    structural_columns = [
        "frac_P",
        "frac_PT",
        "frac_T",
        "frac_F",

        "mean_peo_oxygen_cn",
        "mean_peo_chain_cn",
        "mean_tfsi_oxygen_cn",
        "mean_tfsi_molecular_cn",
        "mean_total_oxygen_cn",

        "fraction_coordinated_tfsi_bridging",
        "fraction_all_tfsi_bridging",
        "fraction_metals_tfsi_bridged",

        "fraction_coordinating_peo_chains_shared",
        "fraction_all_peo_chains_shared",
        "fraction_coordinating_peo_chains_local_bridging",
        "fraction_all_peo_chains_local_bridging",

        "fraction_metals_shared_peo_chain",
        "fraction_metals_local_peo_bridged",
        "fraction_metals_remote_peo_shared",

        "mean_metals_per_coordinating_peo_chain",
        "max_metals_on_one_peo_chain",

        "fraction_metals_any_bridge",
        "fraction_metals_both_peo_tfsi_bridged",
        "fraction_metals_peo_only_bridged",
        "fraction_metals_tfsi_only_bridged",

        "mean_cluster_metals_number_average",
        "mean_cluster_metals_weight_average",
        "largest_cluster_n_metals",
        "largest_cluster_metal_fraction",
        "fraction_metals_in_multi_metal_clusters",
        "fraction_single_metal_clusters",
    ]

    available_structural_columns = [
        column
        for column in structural_columns
        if column in frames.columns
    ]

    missing_columns = sorted(
        set(structural_columns)
        - set(available_structural_columns)
    )

    if missing_columns:
        print(
            "\nWarning: the following frame-summary columns "
            "were not found:"
        )

        for column in missing_columns:
            print(f"  - {column}")

    block_frame_means = (
        frames
        .groupby("block", as_index=False)[
            available_structural_columns
        ]
        .mean()
    )

    block_frame_means.insert(
        0,
        "composition",
        composition,
    )

    block_frame_means.insert(
        0,
        "metal_species",
        metal,
    )

    block_frame_means.insert(
        0,
        "system",
        system_name,
    )

    block_frame_means.to_csv(
        system_output_dir
        / f"block_means_{system_name}.csv",
        index=False,
    )

    overall_summary = block_statistics(
        block_frame_means,
        available_structural_columns,
    )

    overall_summary.insert(
        0,
        "composition",
        composition,
    )

    overall_summary.insert(
        0,
        "metal_species",
        metal,
    )

    overall_summary.insert(
        0,
        "system",
        system_name,
    )

    overall_summary.to_csv(
        system_output_dir
        / f"overall_summary_{system_name}.csv",
        index=False,
    )

    # ========================================================
    # 2. COORDINATION STATE POPULATIONS
    # ========================================================

    state_order = [
        "P",
        "PT",
        "T",
        "F",
    ]

    state_block = (
        master
        .groupby(
            ["block", "coordination_state"]
        )
        .size()
        .rename("count")
        .reset_index()
    )

    state_totals = (
        state_block
        .groupby("block")["count"]
        .transform("sum")
    )

    state_block["fraction"] = (
        state_block["count"]
        / state_totals
    )

    state_block = (
        state_block
        .pivot(
            index="block",
            columns="coordination_state",
            values="fraction",
        )
        .fillna(0.0)
        .reindex(
            columns=state_order,
            fill_value=0.0,
        )
        .reset_index()
    )

    state_block.insert(
        0,
        "composition",
        composition,
    )

    state_block.insert(
        0,
        "metal_species",
        metal,
    )

    state_block.insert(
        0,
        "system",
        system_name,
    )

    state_block.to_csv(
        system_output_dir
        / f"state_block_fractions_{system_name}.csv",
        index=False,
    )

    state_summary_rows = []

    for state in state_order:
        values = state_block[state]

        state_summary_rows.append({
            "system": system_name,
            "metal_species": metal,
            "composition": composition,
            "state": state,
            "mean_fraction": values.mean(),
            "block_std": values.std(ddof=1),
            "block_sem": (
                values.std(ddof=1)
                / np.sqrt(len(values))
            ),
        })

    state_summary = pd.DataFrame(
        state_summary_rows
    )

    state_summary.to_csv(
        system_output_dir
        / f"state_summary_{system_name}.csv",
        index=False,
    )

    # ========================================================
    # 3. COORDINATION-NUMBER DISTRIBUTIONS
    # ========================================================

    coordination_columns = [
        "n_peo_oxygen",
        "n_peo_chains",
        "n_tfsi_oxygen",
        "n_tfsi_molecules",
        "total_oxygen_cn",
    ]

    coordination_distributions = []

    for column in coordination_columns:

        table = safe_probability_table(
            master[column],
            "coordination_number",
        )

        table.insert(
            0,
            "metric",
            column,
        )

        table.insert(
            0,
            "composition",
            composition,
        )

        table.insert(
            0,
            "metal_species",
            metal,
        )

        table.insert(
            0,
            "system",
            system_name,
        )

        coordination_distributions.append(
            table
        )

    coordination_distribution = pd.concat(
        coordination_distributions,
        ignore_index=True,
    )

    coordination_distribution.to_csv(
        system_output_dir
        / f"coordination_distributions_{system_name}.csv",
        index=False,
    )

    # ========================================================
    # 4. JOINT PEO-TFSI COORDINATION MAP
    # ========================================================

    joint_counts = (
        master
        .groupby(
            [
                "n_peo_oxygen",
                "n_tfsi_molecules",
            ]
        )
        .size()
        .rename("count")
        .reset_index()
    )

    joint_counts["probability"] = (
        joint_counts["count"]
        / joint_counts["count"].sum()
    )

    joint_counts.insert(
        0,
        "composition",
        composition,
    )

    joint_counts.insert(
        0,
        "metal_species",
        metal,
    )

    joint_counts.insert(
        0,
        "system",
        system_name,
    )

    joint_counts.to_csv(
        system_output_dir
        / f"joint_peo_tfsi_coordination_{system_name}.csv",
        index=False,
    )

    # ========================================================
    # 5. TFSI DENTICITY DISTRIBUTION
    # ========================================================

    denticity_values = []

    for value in master["tfsi_denticity"]:
        denticity_values.extend(
            parse_denticity_json(value)
        )

    if denticity_values:
        denticity_distribution = (
            safe_probability_table(
                pd.Series(denticity_values),
                "denticity",
            )
        )
    else:
        denticity_distribution = pd.DataFrame(
            columns=[
                "denticity",
                "count",
                "probability",
            ]
        )

    denticity_distribution.insert(
        0,
        "composition",
        composition,
    )

    denticity_distribution.insert(
        0,
        "metal_species",
        metal,
    )

    denticity_distribution.insert(
        0,
        "system",
        system_name,
    )

    denticity_distribution.to_csv(
        system_output_dir
        / f"tfsi_denticity_distribution_{system_name}.csv",
        index=False,
    )

    # ========================================================
    # 6. TFSI BRIDGING DISTRIBUTION
    # ========================================================

    tfsi_metal_count_distribution = (
        safe_probability_table(
            tfsi_bridging["n_coordinating_metals"],
            "n_coordinating_metals",
        )
    )

    tfsi_metal_count_distribution.insert(
        0,
        "composition",
        composition,
    )

    tfsi_metal_count_distribution.insert(
        0,
        "metal_species",
        metal,
    )

    tfsi_metal_count_distribution.insert(
        0,
        "system",
        system_name,
    )

    tfsi_metal_count_distribution.to_csv(
        system_output_dir
        / f"tfsi_metals_per_anion_{system_name}.csv",
        index=False,
    )

    # ========================================================
    # 7. PEO CHAIN OCCUPANCY AND BRIDGING
    # ========================================================

    peo_metals_per_chain_distribution = (
        safe_probability_table(
            peo_bridging["n_coordinating_metals"],
            "n_coordinating_metals",
        )
    )

    peo_metals_per_chain_distribution.insert(
        0,
        "composition",
        composition,
    )

    peo_metals_per_chain_distribution.insert(
        0,
        "metal_species",
        metal,
    )

    peo_metals_per_chain_distribution.insert(
        0,
        "system",
        system_name,
    )

    peo_metals_per_chain_distribution.to_csv(
        system_output_dir
        / f"peo_metals_per_chain_{system_name}.csv",
        index=False,
    )

    shared_peo_pairs = peo_bridging[
        peo_bridging["n_metal_pairs"] > 0
    ].copy()

    if len(shared_peo_pairs) > 0:

        separation_distribution = (
            shared_peo_pairs[
                "minimum_pair_eo_separation"
            ]
            .dropna()
            .astype(int)
        )

        separation_distribution = (
            safe_probability_table(
                separation_distribution,
                "minimum_eo_separation",
            )
        )

    else:
        separation_distribution = pd.DataFrame(
            columns=[
                "minimum_eo_separation",
                "count",
                "probability",
            ]
        )

    separation_distribution.insert(
        0,
        "composition",
        composition,
    )

    separation_distribution.insert(
        0,
        "metal_species",
        metal,
    )

    separation_distribution.insert(
        0,
        "system",
        system_name,
    )

    separation_distribution.to_csv(
        system_output_dir
        / f"peo_minimum_eo_separation_{system_name}.csv",
        index=False,
    )

    # ========================================================
    # 8. CLUSTER-SIZE DISTRIBUTIONS
    # ========================================================

    cluster_number_distribution = (
        clusters
        .groupby("n_metals")
        .size()
        .rename("cluster_count")
        .reset_index()
        .sort_values("n_metals")
    )

    cluster_number_distribution[
        "cluster_probability"
    ] = (
        cluster_number_distribution["cluster_count"]
        / cluster_number_distribution[
            "cluster_count"
        ].sum()
    )

    cluster_number_distribution[
        "metal_weight"
    ] = (
        cluster_number_distribution["n_metals"]
        * cluster_number_distribution["cluster_count"]
    )

    cluster_number_distribution[
        "metal_fraction"
    ] = (        cluster_number_distribution["metal_weight"]
        / cluster_number_distribution[
            "metal_weight"
        ].sum()
    )

    cluster_number_distribution.insert(
        0,
        "composition",
        composition,
    )

    cluster_number_distribution.insert(
        0,
        "metal_species",
        metal,
    )

    cluster_number_distribution.insert(
        0,
        "system",
        system_name,
    )

    cluster_number_distribution.to_csv(
        system_output_dir
        / f"cluster_size_distribution_{system_name}.csv",
        index=False,
    )

    # ========================================================
    # 9. BASIC SYSTEM FIGURES
    # ========================================================

    make_system_coordination_plot(
        system_name,
        metal,
        composition,
        coordination_distribution,
    )

    make_system_joint_map(
        system_name,
        metal,
        composition,
        joint_counts,
    )

    make_system_denticity_plot(
        system_name,
        metal,
        composition,
        denticity_distribution,
    )

    make_system_cluster_plot(
        system_name,
        metal,
        composition,
        cluster_number_distribution,
    )

    print(
        f"Completed structural summary for {system_name}."
    )

    return {
        "overall_summary": overall_summary,
        "state_summary": state_summary,
        "coordination_distribution":
            coordination_distribution,
        "joint_coordination": joint_counts,
        "denticity_distribution":
            denticity_distribution,
        "tfsi_metals_per_anion":
            tfsi_metal_count_distribution,
        "peo_metals_per_chain":
            peo_metals_per_chain_distribution,
        "peo_eo_separation":
            separation_distribution,
        "cluster_distribution":
            cluster_number_distribution,
        "block_means":
            block_frame_means,
    }


